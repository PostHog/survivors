export const CHARS = Object.keys(G).join('');
const SUPPORTED = new Set(CHARS);
const PER_ROW = 16;

/** Map typographic characters to ones the font has; drop anything else (emoji etc.). */
export function cleanText(s: unknown): string {
  let t = String(s ?? '')
    .replace(/[‘’‚′]/g, "'")
    .replace(/[“”„″]/g, '"')
    .replace(/[–—−]/g, '-')
    .replace(/…/g, '...')
    .replace(/×/g, 'x')
    .replace(/[ \t]/g, ' ')
    .normalize('NFD').replace(/[̀-ͯ]/g, '');
  let out = '';
  for (const ch of t) out += ch === '\n' || SUPPORTED.has(ch) ? ch : '';
  return out.replace(/ {2,}/g, ' ');
}

/** Draws the glyph sheet onto a canvas texture and registers the RetroFont. Call once in preload/create. */
export function registerFont(scene: Phaser.Scene) {
  if (scene.cache.bitmapFont.exists(FONT)) return;
  const chars = [...CHARS];
  const rows = Math.ceil(chars.length / PER_ROW);
  const tex = scene.textures.createCanvas(FONT + '-sheet', PER_ROW * CHAR_W, rows * LINE_H)!;
  const ctx = tex.getContext();
  ctx.fillStyle = '#ffffff';
  chars.forEach((ch, i) => {
    const ox = (i % PER_ROW) * CHAR_W, oy = Math.floor(i / PER_ROW) * LINE_H;
    G[ch].forEach((row, y) => [...row].forEach((c, x) => c === '#' && ctx.fillRect(ox + x, oy + y + 1, 1, 1)));
  });
  tex.refresh();
  const entry = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: FONT + '-sheet', width: CHAR_W, height: LINE_H, chars: CHARS, charsPerRow: PER_ROW,
    offset: { x: 0, y: 0 }, spacing: { x: 0, y: 0 }, lineSpacing: 0,
  } as unknown as Phaser.Types.GameObjects.BitmapText.RetroFontConfig);
  scene.cache.bitmapFont.add(FONT, entry);
}
