// Runs after the game build: adds what the static-asset layer and the Worker need around it.
//   public/_headers       security + caching headers for the public root game (static assets are served without the Worker)
//   public/robots.txt, sitemap.xml   the public home page and guide are for search engines; everything else is kept out by noindex (see below)
//   src/generated/csp.json  the same policies for the Worker, which serves gated games itself (and so can't use _headers)
//
// One policy, defined here. The game needs no inline script, except the player's guide (guide.html, an iframe), which has one
// small inline script: its hash is allowed on that page only, so nothing else can run inline anywhere.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const pub = path.join(root, 'public');

const guide = fs.readFileSync(path.join(pub, 'guide.html'), 'utf8');
// Structured data (type="application/ld+json") is not executed, so it needs no hash.
const inline = [...guide.matchAll(/<script(?![^>]*\bsrc=)(?![^>]*ld\+json)[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
const hashes = inline.map((body) => `'sha256-${crypto.createHash('sha256').update(body).digest('base64')}'`);
if (hashes.length === 0) console.warn('guide.html has no inline script any more: the guide policy could be dropped');

const csp = (scriptSrc) =>
  [
    "default-src 'self'",
    `script-src ${scriptSrc}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "media-src 'self' blob: data:",
    "connect-src 'self' https://*.posthog.com https://*.i.posthog.com",
    "worker-src 'self' blob:",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'self'",
  ].join('; ');
// The admin app talks only to this origin (the Worker calls the AI providers, so a person's API key never goes to a third party from
// the browser) and may not be framed by anyone.
const admin = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'self'",
  "frame-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ');
// The game's analytics (game/shared/src/analytics.ts) loads PostHog's script from the assets twin of the ingestion host, so that host may serve scripts
// to the game, and nothing else may. Events go out through connect-src, which already allows PostHog.
const posthog = JSON.parse(fs.readFileSync(path.join(root, 'game/site.json'), 'utf8')).posthog;
const analyticsScripts = posthog
  ? ` ${(posthog.host ?? 'https://us.i.posthog.com').replace('.i.posthog.com', '-assets.i.posthog.com')}`
  : '';
const policies = { game: csp(`'self'${analyticsScripts}`), guide: csp(`'self' ${hashes.join(' ')}`), admin };

const headers = `# generated by scripts/assemble.mjs: do not edit
# The home page (/) and /guide are public and indexable. Everything else that is served from here is not a page for search results.
/_admin/*
  X-Robots-Tag: noindex, nofollow, noarchive

/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Content-Security-Policy: ${policies.game}

# guide.html is canonicalised to /guide by the asset layer: the browser ends up on /guide, so both need the guide policy
/guide.html
  ! Content-Security-Policy
  Content-Security-Policy: ${policies.guide}

/guide
  ! Content-Security-Policy
  Content-Security-Policy: ${policies.guide}

/assets/index-*
  Cache-Control: public, max-age=31536000, immutable

# the admin app's files are content-hashed too
/_admin/assets/*
  Cache-Control: public, max-age=31536000, immutable
`;
fs.writeFileSync(path.join(pub, '_headers'), headers);
// Nothing is disallowed on purpose: a prospect's game and the admin answer with noindex (the Worker adds it to every response it
// makes), and a crawler that is blocked by robots.txt never sees that header. Only the Sitemap line matters here.
const origin = JSON.parse(fs.readFileSync(path.join(root, 'game/site.json'), 'utf8')).site;
fs.writeFileSync(path.join(pub, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${origin}/sitemap.xml\n`);
const urls = ['/', '/guide'].map((u) => `  <url><loc>${origin}${u}</loc></url>`).join('\n');
fs.writeFileSync(
  path.join(pub, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`,
);
fs.mkdirSync(path.join(root, 'src/generated'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/generated/csp.json'), `${JSON.stringify(policies, null, 2)}\n`);
console.log(`assembled public/ (guide inline scripts allowed by hash: ${hashes.length})`);
